CREATE TABLE couriers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 9011) PRIMARY KEY,
    user_id    BIGINT UNIQUE,
    name       VARCHAR(128)           NOT NULL,
    phone      VARCHAR(32)            NOT NULL,
    status     VARCHAR(16)            NOT NULL CHECK (status IN ('OFFLINE', 'AVAILABLE', 'BUSY')),
    position   geography(Point, 4326),
    updated_at TIMESTAMPTZ            NOT NULL,
    version    BIGINT                 NOT NULL DEFAULT 0
);

CREATE INDEX idx_couriers_available_position ON couriers USING GIST (position) WHERE status = 'AVAILABLE';

